import { z } from "zod";
import { PaginationQuery } from "./pagination";

// Invoice contracts shared by /api/v1/invoices and the web UI.
// Money travels as decimal strings ("1250.00"); the server does all math in integer cents.

export const INVOICE_STATUSES = ["draft", "issued", "partially_paid", "paid", "overdue", "void"] as const;
export type InvoiceStatus = (typeof INVOICE_STATUSES)[number];
export const INVOICE_STATUS_LABELS: Record<InvoiceStatus, string> = {
  draft: "Draft",
  issued: "Issued",
  partially_paid: "Partially paid",
  paid: "Paid",
  overdue: "Overdue",
  void: "Void",
};

export const INVOICE_TYPES = ["standard", "deposit", "progress", "final"] as const;
export type InvoiceType = (typeof INVOICE_TYPES)[number];
export const INVOICE_TYPE_LABELS: Record<InvoiceType, string> = {
  standard: "Standard",
  deposit: "Deposit",
  progress: "Progress",
  final: "Final",
};

const amount = (label: string) =>
  z
    .string()
    .trim()
    .regex(/^\d{1,10}(\.\d{1,2})?$/, `Enter ${label} like 250 or 250.50.`);
const ymd = z.string().regex(/^\d{4}-\d{2}-\d{2}$/, "Enter a valid date.");
const optionalText = (max: number) =>
  z
    .string()
    .trim()
    .max(max)
    .nullish()
    .transform((v) => v || null);

export const InvoiceItemInput = z.object({
  description: z.string().trim().min(1, "Describe the line item.").max(255),
  quantity: z
    .string()
    .trim()
    .regex(/^\d{1,8}(\.\d{1,3})?$/, "Enter a quantity like 1 or 2.5.")
    .refine((v) => Number(v) > 0, "Quantity must be more than 0."),
  unit: z.string().trim().max(30).default("ea").transform((v) => v || "ea"),
  unit_price: amount("a price"),
  taxable: z.boolean().default(true),
});
export type InvoiceItemInput = z.input<typeof InvoiceItemInput>;

export const InvoiceInput = z
  .object({
    customer_id: z.string().uuid("Choose a customer."),
    project_id: z
      .string()
      .uuid()
      .or(z.literal(""))
      .nullish()
      .transform((v) => v || null),
    invoice_type: z.enum(INVOICE_TYPES).default("standard"),
    issue_date: ymd,
    due_date: ymd,
    tax_rate: z
      .string()
      .trim()
      .regex(/^\d{1,2}(\.\d{1,3})?$|^100(\.0{1,3})?$/, "Enter a tax rate like 8.25.")
      .default("0"),
    discount: amount("a discount").default("0"),
    customer_notes: optionalText(2000),
    terms: optionalText(2000),
    items: z.array(InvoiceItemInput).min(1, "Add at least one line item.").max(100, "Up to 100 line items."),
  })
  .refine((v) => v.due_date >= v.issue_date, { path: ["due_date"], message: "Due date can't be before the invoice date." });
export type InvoiceInput = z.input<typeof InvoiceInput>;
export type InvoiceData = z.output<typeof InvoiceInput>;

export const INVOICE_TABS = ["outstanding", "draft", "overdue", "paid", "void", "all"] as const;
export type InvoiceTab = (typeof INVOICE_TABS)[number];
export const INVOICE_SORTS = ["invoice_number", "customer", "issue_date", "due_date", "total", "balance_due"] as const;
export type InvoiceSort = (typeof INVOICE_SORTS)[number];

export const InvoiceListQuery = PaginationQuery.extend({
  q: z.string().trim().max(100).optional(),
  tab: z.enum(INVOICE_TABS).default("all"),
  customer_id: z.string().uuid().optional(),
  project_id: z.string().uuid().optional(),
  type: z.enum([...INVOICE_TYPES, "all"]).default("all"),
  sort: z.enum(INVOICE_SORTS).default("issue_date"),
  dir: z.enum(["asc", "desc"]).default("desc"),
});
export type InvoiceListQuery = z.input<typeof InvoiceListQuery>;

export const RecordPaymentInput = z.object({
  amount: amount("an amount").refine((v) => Number(v) > 0, "Amount must be more than 0."),
  paid_on: ymd,
  method: z.string().trim().min(1, "Choose how it was paid.").max(64),
  reference: optionalText(120),
  notes: optionalText(1000),
  /** Generated by the client per form; a retried submit returns the first result instead of paying twice. */
  idempotency_key: z.string().trim().min(8).max(160),
});
export type RecordPaymentInput = z.input<typeof RecordPaymentInput>;

export const VoidInput = z.object({ reason: z.string().trim().min(3, "Give a short reason.").max(255) });
export type VoidInput = z.input<typeof VoidInput>;

export type InvoiceListItem = {
  id: string;
  invoice_number: string;
  status: InvoiceStatus;
  invoice_type: InvoiceType;
  customer: { id: string; display_name: string };
  project: { id: string; project_number: string; name: string } | null;
  issue_date: string;
  due_date: string | null;
  total: string;
  amount_paid: string;
  balance_due: string;
  /** Days past due (only when overdue). */
  days_overdue: number | null;
};

export type InvoiceSummary = { outstanding: string; overdue: string; paid_30d: string; drafts: number };

export type InvoiceListPage = {
  items: InvoiceListItem[];
  page: number;
  per_page: number;
  total: number;
  counts: Record<InvoiceTab, number>;
  summary: InvoiceSummary;
  can_write: boolean;
};

export type InvoiceItemDto = {
  id: string;
  description: string;
  quantity: string;
  unit: string;
  unit_price: string;
  line_subtotal: string;
  taxable: boolean;
  tax_amount: string;
};

export type InvoicePaymentDto = {
  id: string;
  amount: string;
  paid_on: string;
  method: string | null;
  method_label: string | null;
  reference: string | null;
  notes: string | null;
  status: "succeeded" | "cancelled" | "pending" | "failed" | "refunded" | "partially_refunded" | "initiated";
  provider: "manual" | "stripe";
  recorded_by: string | null;
  created_at: string;
};

export type Party = {
  name: string;
  email: string | null;
  phone: string | null;
  address_lines: string[];
};

export type InvoiceDetail = InvoiceListItem & {
  currency: string;
  subtotal: string;
  discount_total: string;
  tax_rate: string;
  tax_total: string;
  customer_notes: string | null;
  terms: string | null;
  void_reason: string | null;
  issued_at: string | null;
  paid_at: string | null;
  voided_at: string | null;
  items: InvoiceItemDto[];
  payments: InvoicePaymentDto[];
  bill_to: Party;
  from: Party & { has_logo: boolean };
  can: { edit: boolean; issue: boolean; record_payment: boolean; void: boolean; delete: boolean };
};
